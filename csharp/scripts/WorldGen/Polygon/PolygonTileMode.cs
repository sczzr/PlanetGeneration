namespace PlanetGeneration.WorldGen.Polygon;

/// <summary>
/// 地块系统模式：控制"哪一层是地块属性的真源"，以及"哪些图层用多边形渲染"。
///
/// 引入这个开关是为了保证改造过程中原有功能始终可用：
/// 任何阶段出问题都能一键退回 <see cref="Raster"/>，而不需要回滚代码。
/// 三个取值都有实际行为差异，没有占位项。
/// </summary>
public enum PolygonTileMode
{
    /// <summary>
    /// 全部走栅格：地块层根本不构建，等同于改造前的行为。
    /// 用于回归基线与故障回退。
    /// </summary>
    Raster = 0,

    /// <summary>
    /// 混合：**离散分类图层**（生物群系 / 岩石 / 矿产 / 地貌 / 板块）用多边形渲染，
    /// **连续场图层**（地形总览 / 温度 / 湿度 / 风场 / 高程 / 河流）继续走栅格。
    ///
    /// 为什么这样分：离散量"一个地块只有一种取值"，用多边形填充不会在格子边界上混色；
    /// 连续量需要逐像素的渐变与等值线，栅格更合适。
    /// </summary>
    Hybrid = 1,

    /// <summary>
    /// **游戏地图就是多边形单元格**（默认）。
    ///
    /// 所有能按地块属性着色的图层都用多边形填充：地形总览 / 板块 / 温度 / 河流 / 湿度 /
    /// 高程 / 岩石 / 矿产 / 生物群系 / 地貌 / 地块划分。
    /// 连续场图层在这里是"逐地块取一个采样值再平铺"——这正是单元格地图的表现方式，
    /// 代价是失去逐像素的渐变，收益是地图的构成单元与地块模型完全一致。
    ///
    /// 生态 / 文明 / 贸易 / 城市 / 风场 仍走栅格：它们的数据源要么是逐像素的模拟器输出，
    /// 要么需要在地图上叠加箭头/标记，属于 P4 后续步骤。
    /// </summary>
    Cells = 2,

    /// <summary>
    /// 在 <see cref="Cells"/> 的基础上再给地块加一圈边界描边。
    /// 描边会压住一部分属性色，所以单独一档而不是默认开启。
    /// </summary>
    Outlined = 3,
}
